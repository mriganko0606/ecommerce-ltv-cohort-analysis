"""Run the full project end to end:

    1. generate synthetic transactional data   (data/raw/*.csv)
    2. load SQLite + run the SQL pipeline       (data/ecommerce.db)
    3. RFM, cohort, KPI and CLV analysis         (reports/figures, reports/tables)
    4. export the Power BI dataset               (powerbi/data/*.csv)
    5. write a findings summary                  (reports/findings.md)

Usage:  python run_pipeline.py
"""
from src import (build_database, cohort_analysis, export_powerbi, generate_data,
                 kpi_analysis, ltv_analysis, rfm_analysis)
from src.config import ROOT


def write_findings(rfm, cohort, kpi, ltv):
    overall = ltv["overall"]
    channels = ltv["by_channel"]
    best, worst = channels.index[0], channels.index[-1]
    seg = rfm["segments"][["segment", "customers", "pct_customers", "pct_revenue", "avg_monetary"]]

    lines = [
        "# Key Findings",
        "",
        "_Auto-generated by `run_pipeline.py`. Synthetic data, Jan 2023 - Dec 2024._",
        "",
        "## Business overview",
        f"- Revenue: **${kpi['revenue_total']:,.0f}** from **{kpi['orders_total']:,}** completed orders "
        f"and **{rfm['customers']:,}** customers (AOV ${kpi['aov']:,.2f}, gross margin {kpi['gross_margin_pct']:.1f}%).",
        f"- 2024 revenue grew **{kpi['yoy_growth_pct']:.1f}%** year over year "
        f"(${kpi['revenue_2023']:,.0f} -> ${kpi['revenue_2024']:,.0f}); average MoM growth in 2024 was "
        f"{kpi['avg_mom_growth_2024']:.1f}%.",
        "",
        "## RFM segmentation",
        f"- **Champions** are {rfm['high_value_pct_customers']:.1f}% of customers but generate "
        f"**{rfm['high_value_pct_revenue']:.1f}% of total revenue**.",
        f"- The top 20% of customers by spend drive {rfm['top20_pct_revenue']:.1f}% of revenue; "
        f"the top 10% alone drive {rfm['top10_pct_revenue']:.1f}%.",
        "",
        seg.to_markdown(index=False),
        "",
        "## Cohort retention",
        f"- Average retention: month 1 **{cohort['retention_m1']:.1f}%**, month 3 {cohort['retention_m3']:.1f}%, "
        f"month 6 {cohort['retention_m6']:.1f}%, month 12 {cohort['retention_m12']:.1f}%.",
        f"- Most churn happens right after the first purchase: {100 - cohort['retention_m1']:.0f}% of customers do not buy again "
        "the following month, so the first 30 days are the biggest retention opportunity.",
        f"- 2023 cohorts generated an average of **${cohort['ltv_12m_per_customer']:,.0f}** revenue per customer "
        "in their first 12 months.",
        "",
        "## Customer lifetime value",
        f"- Annual churn rate: **{overall['annual_churn_rate_pct']:.1f}%** -> expected lifespan "
        f"{overall['expected_lifespan_years']:.2f} years.",
        f"- Annual gross margin per active customer: ${overall['annual_margin_per_customer']:,.2f} -> "
        f"**predicted CLV ${overall['predicted_clv']:,.2f}** (gross-margin basis).",
        f"- Best channel: **{best}** (CLV ${channels.loc[best, 'predicted_clv']:,.0f}); weakest: "
        f"**{worst}** (CLV ${channels.loc[worst, 'predicted_clv']:,.0f}). Acquisition budgets should "
        "be weighed against these values.",
        "",
        channels[["customers", "annual_churn_rate_pct", "expected_lifespan_years",
                  "annual_margin_per_customer", "predicted_clv"]].to_markdown(),
        "",
    ]
    path = ROOT / "reports" / "findings.md"
    path.write_text("\n".join(lines), encoding="utf-8")
    print("  saved reports/findings.md")


def main():
    print("[1/5] Generating data");        generate_data.main()
    print("[2/5] Building database");       build_database.main()
    print("[3/5] Running analysis")
    rfm = rfm_analysis.main()
    cohort = cohort_analysis.main()
    kpi = kpi_analysis.main()
    ltv = ltv_analysis.main()
    print("[4/5] Exporting Power BI data"); export_powerbi.main()
    print("[5/5] Writing findings");        write_findings(rfm, cohort, kpi, ltv)
    print("Done.")


if __name__ == "__main__":
    main()
